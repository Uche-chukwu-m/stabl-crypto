// npm run export-abi (inside contracts/)
// Copies the compiled vault's interface into the app, so the app and the
// deployed contract can never drift apart silently. Run after `npm run build`.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(readFileSync(new URL("../artifacts/src/StablVault.sol/StablVault.json", import.meta.url), "utf8"));
const out = new URL("../../lib/chain/vault-abi.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by contracts/scripts/export-abi.mjs from contracts/src/StablVault.sol. Do not edit.\n` +
    `export const vaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${artifact.abi.length} entries to lib/chain/vault-abi.ts`);
